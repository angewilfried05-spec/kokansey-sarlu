import java.util.Properties

val baseUrlDebug = (project.findProperty("BASE_URL_DEBUG") as String?)?.trim().orEmpty().ifEmpty { "http://10.0.2.2:3000" }
val baseUrlRelease = (project.findProperty("BASE_URL_RELEASE") as String?)?.trim().orEmpty().ifEmpty { baseUrlDebug }

val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}
val hasReleaseSigning = keystorePropertiesFile.exists()
    && !keystoreProperties.getProperty("storeFile").isNullOrBlank()

